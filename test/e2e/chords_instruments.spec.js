'use strict';
const { test, expect } = require('@playwright/test');
const { mockApp, STATES } = require('./support/mock-app');

test('CH-B 건반 5모드의 MIDI 표시·재생·입력·악기 전환 취소', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => {
    window.__keyboardAudio = [];
    const original = AudioContext.prototype.createOscillator;
    AudioContext.prototype.createOscillator = function (...args) {
      const oscillator = original.apply(this, args);
      let plannedFrequency;
      const setFrequency = oscillator.frequency.setValueAtTime.bind(oscillator.frequency);
      oscillator.frequency.setValueAtTime = (frequency, when) => { plannedFrequency = frequency; return setFrequency(frequency, when); };
      const start = oscillator.start.bind(oscillator);
      oscillator.start = (...values) => { window.__keyboardAudio.push({ type: oscillator.type, frequency: plannedFrequency }); return start(...values); };
      return oscillator;
    };
  });
  await page.clock.install();
  await mockApp(page, STATES.guest);
  await page.goto('/chords.html#scale');
  await page.locator('#instrument-keyboard').click();
  await expect(page.locator('#sc-board [data-midi="48"]')).toHaveAttribute('data-pressed', 'true');
  await expect(page.locator('#sc-board [data-midi="49"]')).toHaveAttribute('data-pressed', 'false');
  await page.locator('#sc-play').click();
  await page.clock.runFor(400);
  await expect(page.locator('#sc-board [data-now="true"]')).toHaveCount(1);
  expect(await page.evaluate(() => window.__keyboardAudio.some((o) => o.type === 'sine' && Math.abs(o.frequency - 130.8128) < 0.01))).toBe(true);
  await page.locator('#tab-tone').click();
  await page.locator('#tone-play').click();
  await page.clock.runFor(400);
  await expect(page.locator('#tone-board [data-now="true"]')).toHaveCount(1);
  await page.locator('#tab-reint').click();
  await page.locator('#ri-clear').click();
  await expect(page.locator('#ri-board [data-pressed="true"]')).toHaveCount(0);
  await page.locator('#ri-keyboard-note').selectOption('69');
  await page.locator('#ri-keyboard-toggle').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#ri-board [data-midi="69"]')).toHaveAttribute('data-pressed', 'true');
  expect(await page.evaluate(() => window.__keyboardAudio.some((o) => o.type === 'sine' && o.frequency === 440))).toBe(true);
  await page.locator('#ri-keyboard-toggle').click();
  await expect(page.locator('#ri-board [data-pressed="true"]')).toHaveCount(0);
  await page.locator('#tab-tf').click();
  await expect(page.locator('#a-board svg[data-keyboard]')).toBeVisible();
  await page.locator('#a-vplay').click();
  await page.clock.runFor(100);
  await page.locator('#instrument-bass').click();
  const stopped = await page.evaluate(() => window.__keyboardAudio.length);
  await page.clock.runFor(5000);
  expect(await page.evaluate(() => window.__keyboardAudio.length)).toBe(stopped);
  await expect(page.locator('#tab-scale')).toHaveAttribute('aria-selected', 'true');
  await page.locator('#instrument-keyboard').click();
  await page.evaluate(() => { location.hash = '#prog?c=C%2FE,Dm7,G7'; });
  await expect(page.locator('#pp-boxes svg')).toHaveCount(3);
  await expect(page.locator('#pane-prog svg').first().locator('[data-midi="40"]')).toHaveAttribute('data-pressed', 'true');
  await page.locator('#pp-chips [data-chord="1"]').click();
  await expect(page.locator('#pane-prog svg').first().locator('[data-midi="38"]')).toHaveAttribute('data-hand', 'lh');
  await expect(page.locator('#pane-prog svg').first().locator('[data-midi="50"]')).toHaveAttribute('data-hand', 'rh');
  await expect(page.locator('#pp-open-matrix, #pp-lo, #pp-hi')).toHaveCount(0);
  await page.locator('#pp-play').click();
  await expect(page.locator('#pp-play')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#instrument-guitar').click();
  await expect(page.locator('#pp-play')).toHaveAttribute('aria-pressed', 'false');
  await expect(page.locator('#pp-boxes svg.cb').first()).toBeVisible();
  expect(errors).toEqual([]);
});
